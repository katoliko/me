create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

do $$
declare table_name text;
begin
  foreach table_name in array array['user_roles','site_settings','homepage_sections','lecturas','reflexiones','santos','oraciones','articulos'] loop
    execute format('drop trigger if exists %I on public.%I', table_name || '_updated_at', table_name);
    execute format('create trigger %I before update on public.%I for each row execute function public.set_updated_at()', table_name || '_updated_at', table_name);
  end loop;
end $$;

create or replace function public.set_published_at()
returns trigger language plpgsql as $$
begin
  if new.published and (
    tg_op = 'INSERT' or old.published is distinct from new.published
  ) then
    new.published_at = coalesce(new.published_at, now());
  end if;
  if not new.published then new.published_at = null; end if;
  return new;
end $$;
do $$
declare table_name text;
begin
  foreach table_name in array array['lecturas','reflexiones','santos','oraciones','articulos'] loop
    execute format('drop trigger if exists %I on public.%I', table_name || '_published_at', table_name);
    execute format('create trigger %I before insert or update on public.%I for each row execute function public.set_published_at()', table_name || '_published_at', table_name);
  end loop;
end $$;

alter table public.site_settings enable row level security;
alter table public.homepage_sections enable row level security;
do $$
declare table_name text;
begin
  foreach table_name in array array['lecturas','reflexiones','santos','oraciones','articulos'] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('drop policy if exists %I on public.%I', table_name || '_public_read', table_name);
    execute format('create policy %I on public.%I for select using (published = true or public.is_editor())', table_name || '_public_read', table_name);
    execute format('drop policy if exists %I on public.%I', table_name || '_editor_write', table_name);
    execute format('create policy %I on public.%I for all using (public.is_editor()) with check (public.is_editor())', table_name || '_editor_write', table_name);
  end loop;
end $$;

drop policy if exists user_roles_self_read on public.user_roles;
drop policy if exists user_roles_admin_write on public.user_roles;
create policy user_roles_self_read on public.user_roles for select using (user_id = auth.uid() or public.is_admin());
create policy user_roles_admin_write on public.user_roles for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists site_settings_public_read on public.site_settings;
drop policy if exists site_settings_admin_write on public.site_settings;
create policy site_settings_public_read on public.site_settings for select using (true);
create policy site_settings_admin_write on public.site_settings for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists homepage_sections_public_read on public.homepage_sections;
drop policy if exists homepage_sections_editor_write on public.homepage_sections;
create policy homepage_sections_public_read on public.homepage_sections for select using (published = true);
create policy homepage_sections_editor_write on public.homepage_sections for all using (public.is_editor()) with check (public.is_editor());
