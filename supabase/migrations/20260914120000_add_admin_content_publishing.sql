do $$
declare table_name text;
begin
  foreach table_name in array array['lecturas','reflexiones','santos','oraciones','articulos'] loop
    execute format('alter table public.%I add column if not exists published boolean not null default true', table_name);
    execute format('alter table public.%I add column if not exists published_at timestamptz', table_name);
    execute format('alter table public.%I add column if not exists updated_at timestamptz not null default now()', table_name);
    execute format('create index if not exists %I on public.%I (published)', table_name || '_published_idx', table_name);
  end loop;
end $$;

